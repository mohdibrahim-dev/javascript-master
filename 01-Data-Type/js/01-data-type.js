// JavaScript Has 8 Data Types

// We divide them into 2 categories.

// 1.  Primitive Data Types

// These store a single value.

// String
// Number
// Boolean
// Undefined
// Null
// BigInt
// Symbol

// 2. Non-Primitive Data Type

// Object

// Important:

// Arrays and Functions are technically Objects in JavaScript.


// String
console.log('"Ibrahim" typeof = ', typeof "Ibrahim");

// Number
console.log("type of 21 = ", typeof 21);

// Boolean 
console.log("typeof true = ", typeof true);
console.log("typeof false = ", typeof false);

// Undefined
console.log("typeof undefined = ", typeof undefined );

// null
console.log("typeof null = ", typeof null);

// BigInt 
console.log("type of 1234..........n = ", typeof 123456789n);

// Symbol()
console.log("typeof Symbol() = ", typeof Symbol());

// 
console.log("type of object {.....} = ", typeof {});





